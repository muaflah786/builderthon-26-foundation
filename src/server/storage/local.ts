import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import type { StorageDriver } from "@/server/storage/types";
import { UPLOAD_KEY_PATTERN } from "@/server/storage/validation";

/**
 * Development-only driver: files under ./uploads, served by GET /api/uploads/<key>.
 * Serverless hosts have no persistent disk, so this driver refuses production.
 */
export function createLocalStorage(
  root = path.join(/* turbopackIgnore: true */ process.cwd(), "uploads"),
): StorageDriver & {
  read(key: string): Promise<Uint8Array | null>;
} {
  const fileFor = (key: string) => {
    // Keys are generated by us, but validate again so a path can never escape root.
    if (!UPLOAD_KEY_PATTERN.test(key)) throw new Error(`Invalid storage key: ${key}`);
    // turbopackIgnore: dev-only driver; keep uploads/ out of the server bundle trace.
    return path.join(/* turbopackIgnore: true */ root, key);
  };

  return {
    name: "local",
    async put(key, bytes) {
      await mkdir(/* turbopackIgnore: true */ root, { recursive: true });
      await writeFile(/* turbopackIgnore: true */ fileFor(key), bytes);
    },
    getUrl(key) {
      return `/api/uploads/${key}`;
    },
    async delete(key) {
      await rm(/* turbopackIgnore: true */ fileFor(key), { force: true });
    },
    async read(key) {
      try {
        return new Uint8Array(await readFile(/* turbopackIgnore: true */ fileFor(key)));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw error;
      }
    },
  };
}
